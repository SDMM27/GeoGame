// Bundles the website's flag images in the mobile app so the flag games work offline.
// Source: ../public/flags/*.png
// Output: assets/flags/*.png + src/flags.ts (static requires, Metro can't resolve dynamic paths)
//
// Usage: node scripts/build-flags.mjs
import { copyFileSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = join(root, '..', 'public', 'flags')
const out = join(root, 'assets', 'flags')

const files = readdirSync(source)
  .filter((file) => file.endsWith('.png'))
  .sort()

rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })
for (const file of files) copyFileSync(join(source, file), join(out, file))

const entries = files.map((file) => `  ${JSON.stringify(file.slice(0, -4))}: require('../assets/flags/${file}'),`)
writeFileSync(
  join(root, 'src', 'flags.ts'),
  `// Generated by scripts/build-flags.mjs — do not edit.
const FLAGS: Record<string, number> = {
${entries.join('\n')}
}

// Flag image for an ISO 3166-1 alpha-2 code (any case).
export function getFlag(isoA2: string | null | undefined): number | null {
  return isoA2 ? (FLAGS[isoA2.toLowerCase()] ?? null) : null
}
`
)

console.log(`Bundled ${files.length} flags`)
