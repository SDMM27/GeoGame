// Website labels carry emoji/arrows ("🏆 Scores", "← Accueil"); strip them for native UI.
export function clean(label: string) {
  return label
    .replace(/^[^\p{L}\p{N}]+/u, '')
    .replace(/[\s→←↺✓✗◎]+$/u, '')
    .trim()
}

